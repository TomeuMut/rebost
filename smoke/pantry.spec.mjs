import { test, expect } from '@playwright/test'

test('a product and its initial stock survive a reload', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const response = await page.goto('/', { waitUntil: 'domcontentloaded' })
  expect(response.status()).toBe(200)
  const add = page.getByRole('button', { name: 'Añadir producto', exact: true })
  await expect(add).toBeEnabled()
  await add.click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Nombre del producto').fill('Tomate smoke')
  await dialog.getByLabel('Cantidad inicial', { exact: false }).fill('3')
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const product = page.locator('.product-card').filter({ hasText: 'Tomate smoke' })
  await expect(product.locator('.stock-line strong')).toHaveText('3')
  await product.getByRole('button', { name: 'Consumir', exact: true }).click()
  await dialog.getByLabel('¿Cuánto has utilizado?').fill('1')
  await dialog.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(product.locator('.stock-line strong')).toHaveText('2')
  await page.reload()
  await expect(page.locator('.product-card').filter({ hasText: 'Tomate smoke' }).locator('.stock-line strong')).toHaveText('2')
  await page.getByRole('combobox', { name: 'Idioma', exact: true }).selectOption('en')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page.getByRole('button', { name: 'Add product', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page.locator('.product-card').filter({ hasText: 'Tomate smoke' })).toBeVisible()
  expect(errors).toEqual([])
})
